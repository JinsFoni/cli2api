func TestNativeQuotaFallsBackToWorkerWithoutStore(t *testing.T) {
	var quotaHits int
	worker := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/admin/quota" {
			t.Errorf("path = %s", r.URL.Path)
			w.WriteHeader(http.StatusNotFound)
			return
		}
		quotaHits++
		_, _ = w.Write([]byte(`{"ok":true,"quota":{"isQuotaExceeded":false,"fetchedAt":"now","userQuota":{"total":30,"used":12,"remaining":18,"percentage":40,"unit":"credits"}}}`))
	}))
	defer worker.Close()

	// No native store: the structural fallback reaches the worker hot path.
	client := NewClient(nil)
	client.SetHTTP(worker.Client())
	client.Bind(func(string) (string, bool) { return worker.URL, true }, func() string { return "local-key" })

	snapshot, err := client.QuotaSnapshot(context.Background(), "acc-1", true)
	if err != nil {
		t.Fatal(err)
	}
	if quotaHits != 1 {
		t.Fatalf("worker quota hits = %d", quotaHits)
	}
	if snapshot == nil || snapshot.Remaining != 18 {
		t.Fatalf("snapshot = %+v", snapshot)
	}
}

func TestNativeQuotaFallsBackToWorkerWhenDecodeFails(t *testing.T) {
	upstream := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/api/v2/quota/usage":
			_, _ = w.Write([]byte(`{"userQuota": 17}`))
		case "/admin/quota":
			_, _ = w.Write([]byte(`{"ok":true,"quota":{"isQuotaExceeded":false,"fetchedAt":"now","userQuota":{"total":30,"used":12,"remaining":18,"percentage":40,"unit":"credits"}}}`))
		default:
			t.Errorf("unexpected request %s %s", r.Method, r.URL.Path)
			w.WriteHeader(http.StatusNotFound)
		}
	}))
	defer upstream.Close()

	// Credential decodes fine but upstream answers with an undecodable shape.
	// A shape mismatch means the worker (which calls the same upstream through
	// its own client) would hit it too, but this stays the fallback seam for
	// an older worker cache format: the decode error is classified as a
	// native-attempt failure and surfaces unless the worker succeeds.
	store := &fakeNativeStore{account: cnAccount(upstream.URL), credential: encryptedCredential(t, machineID, nil)}
	client := NewClient(store)
	client.SetHTTP(upstream.Client())
	pointCnAt(t, client, upstream.URL)
	client.Bind(func(string) (string, bool) { return upstream.URL, true }, func() string { return "local-key" })

	_, err := client.QuotaSnapshot(context.Background(), "acc-1", true)
	if err == nil {
		t.Fatal("transient native decode failure must surface, not fall back")
	}
	if !strings.Contains(err.Error(), "decode quota usage") {
		t.Fatalf("err = %v", err)
	}
}

