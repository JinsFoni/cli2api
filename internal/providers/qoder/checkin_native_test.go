func TestCheckinNativeRecoversUnconfirmedClaim(t *testing.T) {
	var claimed atomic.Bool
	upstream := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch {
		case r.Method == http.MethodGet && r.URL.Path == "/sash/api/v1/me/campaigns":
			status := "CLAIMABLE"
			if claimed.Load() {
				status = "CLAIMED"
			}
			_, _ = w.Write([]byte(`{"data":{"campaigns":[{"campaignId":"c1","actionType":"CLAIM_BENEFIT","claimStatus":"` + status + `","benefit":{"kind":"CREDITS","amount":100}}]}}`))
		case r.Method == http.MethodPost && r.URL.Path == "/sash/api/v1/me/campaigns/c1/claim":
			// Upstream accepted the claim but answered without a status; the
			// follow-up list observes CLAIMED.
			claimed.Store(true)
			_, _ = w.Write([]byte(`{"data":{"campaignId":"c1"}}`))
		default:
			t.Errorf("unexpected request %s %s", r.Method, r.URL.Path)
			w.WriteHeader(http.StatusNotFound)
		}
	}))
	defer upstream.Close()

	store := &fakeNativeStore{account: cnAccount(upstream.URL), credential: encryptedCredential(t, machineID, nil)}
	client := newNativeClient(store)
	client.SetHTTP(upstream.Client())
	pointCnAt(t, client, upstream.URL)

	result, err := client.Checkin(context.Background(), "acc-1")
	if err != nil {
		t.Fatal(err)
	}
	// No claim round confirmed CLAIMED directly, but the re-list proved the
	// benefit landed: the already-style recovery path.
	if result.Status != "already" {
		t.Fatalf("result = %+v", result)
	}
}

