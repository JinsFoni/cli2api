type fakeNativeStore struct {
	mu         sync.Mutex
	account    accounts.Account
	credential accounts.NativeCredential
	proxy      string

	getErr  error
	loadErr error

	credentials     []accounts.NativeCredential
	credentialsByID []string
}

func (s *fakeNativeStore) Get(_ context.Context, _ string) (accounts.Account, error) {
	if s.getErr != nil {
		return accounts.Account{}, s.getErr
	}
	return s.account, nil
}

func (s *fakeNativeStore) LoadCredential(_ context.Context, _ string) (accounts.NativeCredential, error) {
	if s.loadErr != nil {
		return accounts.NativeCredential{}, s.loadErr
	}
	return s.credential, nil
}

func (s *fakeNativeStore) SaveCredential(_ context.Context, accountID string, _ string, credential accounts.NativeCredential) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.credentials = append(s.credentials, credential)
	s.credentialsByID = append(s.credentialsByID, accountID)
	return nil
}

func (s *fakeNativeStore) GetSecret(_ context.Context, _ string) (string, bool, error) {
	if s.proxy != "" {
		return s.proxy, true, nil
	}
	return "", false, nil
}

func newNativeClient(store *fakeNativeStore) *Client {
	client := NewClient(store)
	client.Bind(func(string) (string, bool) { return "", false }, func() string { return "" })
	return client
}

func missingClient(store *fakeNativeStore) *Client {
	return newNativeClient(store)
}

func encryptedCredential(t *testing.T, machineID string, mutate func(map[string]any)) accounts.NativeCredential {
	t.Helper()
	user := map[string]any{
		"access_token":  "at-old",
		"refresh_token": "jrt-old",
		"uid":           "u-1",
		"name":          "tester",
		"expire_time":   1893456000000,
	}
	if mutate != nil {
		mutate(user)
	}
	raw, _ := json.Marshal(user)
	return accounts.NativeCredential{
		UserBlob:  []byte(aesCBCEncryptForTest(t, raw, []byte(machineID[:16]))),
		MachineID: machineID,
	}
}

