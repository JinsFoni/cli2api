// vector generated by the reference implementation (qoder2api-hub
// qoder_sign.aes_cbc_encrypt), so a Go-side drift cannot go unnoticed.
func TestDecodeUserBlobReferenceVector(t *testing.T) {
	const blob = "tSve7mpCLUDF1tdUb2cF6opyT62cSEz/Fj1ZOnZzS/J1UG0jrnGjALxfxT/LRmPjujHgMhIgNHrXzJrRCx5JYQYv+BhhE8xA/kLZe9JBZp9QEIDC4BhXmbwrU924q2RkJLfH3AGZ4w68GjwBhLgMTSEpJIGjP1PP0flWOgsFHGg="
	want := userBlob{
		AccessToken:  "at-abc123",
		RefreshToken: "jrt-xyz789",
		UID:          "u-1",
		Name:         "tester",
		ExpireTime:   1893456000000,
	}
	cred, err := decodeUserBlob([]byte(blob), machineID)
	if err != nil {
		t.Fatal(err)
	}
	if cred.AccessToken != want.AccessToken || cred.RefreshToken != want.RefreshToken ||
		cred.UID != want.UID || cred.Name != want.Name || cred.ExpireTime != want.ExpireTime {
		t.Fatalf("decoded = %+v want %+v", cred, want)
	}
	if cred.bearerToken() != want.AccessToken {
		t.Fatalf("bearerToken = %q", cred.bearerToken())
	}
}

