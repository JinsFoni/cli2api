func TestCheckinNative401RefreshesAndRetries(t *testing.T) {
	var listCalls, refreshCalls int
	var secondListAuth string
	upstream := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch {
		case r.Method == http.MethodPost && r.URL.Path == "/api/v1/jobToken/refresh":
			refreshCalls++
			body, _ := io.ReadAll(r.Body)
			if string(body) != `{"refresh_token":"jrt-old"}` {
				t.Errorf("refresh body = %s", body)
			}
			_, _ = w.Write([]byte(`{"token":"at-new","refresh_token":"jrt-new","expires_in":3600000}`))
		case r.Method == http.MethodGet && r.URL.Path == "/sash/api/v1/me/campaigns":
			listCalls++
			if listCalls == 1 {
				w.WriteHeader(http.StatusUnauthorized)
				return
			}
			secondListAuth = strings.TrimPrefix(r.Header.Get("Authorization"), "Bearer ")
			_, _ = w.Write([]byte(`{"campaigns":[{"campaignId":"c1","actionType":"CLAIM_BENEFIT","claimStatus":"CLAIMED","benefit":{"kind":"CREDITS","amount":100}}]}`))
		default:
			t.Errorf("unexpected request %s %s", r.Method, r.URL.Path)
			w.WriteHeader(http.StatusNotFound)
		}
	}))
	defer upstream.Close()

	cred := encryptedCredential(t, machineID, nil)
	store := &fakeNativeStore{account: cnAccount(upstream.URL), credential: cred}
	client := newNativeClient(store)
	client.SetHTTP(upstream.Client())
	pointCnAt(t, client, upstream.URL)

	result, err := client.Checkin(context.Background(), "acc-1")
	if err != nil || result.Status != "already" {
		t.Fatalf("result=%+v err=%v", result, err)
	}
	if refreshCalls != 1 || listCalls != 2 {
		t.Fatalf("refreshCalls=%d listCalls=%d", refreshCalls, listCalls)
	}
	if secondListAuth != "at-new" {
		t.Fatalf("retry auth = %q", secondListAuth)
	}
	// The refreshed blob must be persisted with tokens patched in.
	if len(store.credentials) != 1 {
		t.Fatalf("SaveCredential calls = %d", len(store.credentials))
	}
	saved, err := decodeUserBlob(store.credentials[0].UserBlob, machineID)
	if err != nil {
		t.Fatal(err)
	}
	if saved.AccessToken != "at-new" || saved.RefreshToken != "jrt-new" || saved.ExpireTime == 1893456000000 {
		t.Fatalf("saved credential = %+v", saved)
	}
	if !isEncryptedBlob(store.credentials[0].UserBlob) {
		t.Fatal("encrypted blob must stay encrypted after write-back")
	}
	if store.credentialsByID[0] != "acc-1" {
		t.Fatalf("saved under %q", store.credentialsByID[0])
	}
}

